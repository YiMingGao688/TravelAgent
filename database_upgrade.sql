CREATE DATABASE IF NOT EXISTS travel_agent
  DEFAULT CHARACTER SET utf8mb4
  DEFAULT COLLATE utf8mb4_unicode_ci;

USE travel_agent;

CREATE TABLE IF NOT EXISTS `user` (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(120) NOT NULL UNIQUE,
  password VARCHAR(120) NOT NULL,
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS user_profile (
  id BIGINT NOT NULL PRIMARY KEY,
  user_id VARCHAR(120) NOT NULL UNIQUE,
  city VARCHAR(80),
  transport VARCHAR(80),
  style VARCHAR(80),
  note VARCHAR(500),
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS chat_record (
  id BIGINT NOT NULL PRIMARY KEY,
  user_id VARCHAR(120),
  session_id VARCHAR(120) NOT NULL,
  user_message TEXT,
  ai_response LONGTEXT,
  model VARCHAR(80),
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_chat_session (session_id),
  INDEX idx_chat_user (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS trip_plan (
  id BIGINT NOT NULL PRIMARY KEY,
  user_id VARCHAR(120) NOT NULL,
  session_id VARCHAR(120),
  title VARCHAR(200),
  start_place VARCHAR(120),
  end_place VARCHAR(120),
  content LONGTEXT NOT NULL,
  raw_question TEXT,
  source_type VARCHAR(40) DEFAULT 'AI_CHAT',
  travel_preference VARCHAR(120),
  budget VARCHAR(80),
  days INT,
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_trip_user (user_id),
  INDEX idx_trip_session (session_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS route (
  id BIGINT NOT NULL PRIMARY KEY,
  user_id VARCHAR(120),
  trip_plan_id BIGINT,
  start_point VARCHAR(120) NOT NULL,
  end_point VARCHAR(120) NOT NULL,
  route_type VARCHAR(40),
  route_name VARCHAR(120),
  distance DOUBLE,
  duration INT,
  cost DOUBLE,
  description VARCHAR(1000),
  recommend_reason VARCHAR(1000),
  preference VARCHAR(120),
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_route_points (start_point, end_point),
  INDEX idx_route_user (user_id),
  INDEX idx_route_trip (trip_plan_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

ALTER TABLE `user`
  ADD COLUMN IF NOT EXISTS update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP;

ALTER TABLE user_profile
  ADD COLUMN IF NOT EXISTS created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ADD COLUMN IF NOT EXISTS updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP;

ALTER TABLE chat_record
  ADD COLUMN IF NOT EXISTS user_id VARCHAR(120) NULL,
  MODIFY COLUMN create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP;

ALTER TABLE trip_plan
  ADD COLUMN IF NOT EXISTS raw_question TEXT NULL,
  ADD COLUMN IF NOT EXISTS source_type VARCHAR(40) DEFAULT 'AI_CHAT',
  ADD COLUMN IF NOT EXISTS travel_preference VARCHAR(120) NULL,
  ADD COLUMN IF NOT EXISTS budget VARCHAR(80) NULL,
  ADD COLUMN IF NOT EXISTS days INT NULL,
  MODIFY COLUMN create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  MODIFY COLUMN update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP;

ALTER TABLE route
  ADD COLUMN IF NOT EXISTS user_id VARCHAR(120) NULL,
  ADD COLUMN IF NOT EXISTS trip_plan_id BIGINT NULL,
  ADD COLUMN IF NOT EXISTS cost DOUBLE NULL,
  ADD COLUMN IF NOT EXISTS recommend_reason VARCHAR(1000) NULL,
  ADD COLUMN IF NOT EXISTS preference VARCHAR(120) NULL,
  MODIFY COLUMN create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  MODIFY COLUMN update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP;

CREATE TABLE IF NOT EXISTS smart_service_record (
  id BIGINT NOT NULL PRIMARY KEY,
  user_id VARCHAR(120) NOT NULL,
  service_type VARCHAR(60) NOT NULL,
  title VARCHAR(200),
  start_place VARCHAR(120),
  end_place VARCHAR(120),
  request_payload LONGTEXT,
  response_payload LONGTEXT,
  status VARCHAR(40) DEFAULT 'GENERATED',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_smart_user (user_id),
  INDEX idx_smart_type (service_type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

ALTER TABLE smart_service_record
  ADD COLUMN IF NOT EXISTS title VARCHAR(200) NULL,
  ADD COLUMN IF NOT EXISTS start_place VARCHAR(120) NULL,
  ADD COLUMN IF NOT EXISTS end_place VARCHAR(120) NULL,
  ADD COLUMN IF NOT EXISTS request_payload LONGTEXT NULL,
  ADD COLUMN IF NOT EXISTS response_payload LONGTEXT NULL,
  ADD COLUMN IF NOT EXISTS status VARCHAR(40) DEFAULT 'GENERATED',
